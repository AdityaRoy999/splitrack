// These supplied variants have white artwork on a transparent canvas.
const whiteLogoSources = new Set<ImageSourcePropType>([
  BANK_LOGO_ASSETS.bob,
  BANK_LOGO_ASSETS.dhanlaxmi,
  BANK_LOGO_ASSETS.utkarsh,
  BANK_LOGO_ASSETS.deutsche,
  BANK_LOGO_ASSETS.emiratesnbd,
  BANK_LOGO_ASSETS.kebhana,
  BANK_LOGO_ASSETS.suratdistrict,
]);

export function needsColoredLogoBackground(source: ImageSourcePropType): boolean {
  return whiteLogoSources.has(source);
}

export function getBrandLogoSource(id: string): ImageSourcePropType | undefined {
  const normalized = id.toLowerCase().replace(/[^a-z0-9]/g, '');
  const key = aliases[normalized] ?? normalized;
  return UPI_LOGO_ASSETS[key] ?? BANK_LOGO_ASSETS[key];
}
